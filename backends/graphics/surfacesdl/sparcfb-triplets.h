inline void storeBE(unsigned char *dest,unsigned int word) {
 dest=static_cast<unsigned char *>(__builtin_assume_aligned(dest,4));
#if __BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__
 word=__builtin_bswap32(word);
#endif
 std::memcpy(dest,&word,4);
}
inline void triple(const unsigned char *source,unsigned char *dest,int count) {
 while(count>0 && (reinterpret_cast<uintptr_t>(dest)&3)) {
  dest[0]=dest[1]=dest[2]=*source++;dest+=3;--count;
 }
 while(count>=4) {
  const unsigned int a=source[0],b=source[1],c=source[2],d=source[3];
  storeBE(dest,(triplet[a]<<8)|b);
  storeBE(dest+4,(triplet[b]<<16)|(triplet[c]>>8));
  storeBE(dest+8,(c<<24)|triplet[d]);
  source+=4;dest+=12;count-=4;
 }
 while(count-->0) {dest[0]=dest[1]=dest[2]=*source++;dest+=3;}
}
